def print_logo():
    text = Text(LOGO, style="bold green")
    console.print(text)

def print_model_list(models):
    console.print("\n[bold yellow]Available Local Models:[/bold yellow]")
    for i, model in enumerate(models, 1):
        console.print(f" [bold green]{i}[/bold green]) {model}")
    console.print("[dim]Select a number to choose your model...[/dim]")

def print_user_message(message):
    # Chat box for User
    user_box = Panel(
        Text(message, style="white"),
        title="[bold cyan]👤 You[/bold cyan]",
        border_style="cyan",
        expand=False,
        padding=(0, 1)
    )
    console.print(user_box)

def print_ai_response(response_text):
    # Chat box for AI
    md = Markdown(response_text)
    ai_box = Panel(
        md,
        title="[bold green]🌱 CodeGarden[/bold green]",
        border_style="green",
        padding=(0, 1)
    )
    console.print(ai_box)

def print_error(error_text):
    console.print(f"\n[bold red]❌ Error:[/bold red] {error_text}")

def print_status(status_text):
    console.print(f"[italic yellow]⏳ {status_text}...[/italic yellow]", end="\r")
